def cross(a, b):
    return (
        a[1] * b[2] - a[2] * b[1],
        a[2] * b[0] - a[0] * b[2],
        a[0] * b[1] - a[1] * b[0],
    )


def dist(a, b):
    return math.sqrt(sum((x - y) ** 2 for x, y in zip(a, b)))
